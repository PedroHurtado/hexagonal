CREATE TABLE pedidos (
    id         UUID                     NOT NULL PRIMARY KEY,
    cliente_id UUID                     NOT NULL,
    estado     VARCHAR(20)              NOT NULL,
    creado_en  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version    BIGINT
);

CREATE TABLE lineas_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       UUID           NOT NULL,
    producto_id     VARCHAR(64)    NOT NULL,
    cantidad        INTEGER        NOT NULL,
    precio_unitario NUMERIC(19, 2) NOT NULL,
    moneda          VARCHAR(3)     NOT NULL,
    CONSTRAINT fk_lineas_pedido_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id)
);

CREATE INDEX idx_lineas_pedido_pedido ON lineas_pedido (pedido_id);
